begin;

drop policy "Dueños pueden editar extras" on public.extras;

create policy "extras: dueño gestiona sus extras"
  on public.extras
  for all
  to authenticated
  using (
    restaurant_id in (select r.id from public.restaurants r where r.user_id = auth.uid())
  )
  with check (
    restaurant_id in (select r.id from public.restaurants r where r.user_id = auth.uid())
  );

commit;

